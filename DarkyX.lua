-- Try Lucide first, fall back to whatever image the button already has
local function applyLucide(button, iconName)
	local ok, img, rectOffset, rectSize = pcall(function()
		if not Icons then error("no icons") end
		return resolveIcon(iconName)
	end)
	if ok and img and img ~= "" then
		button.Image = img
		button.ImageRectOffset = rectOffset or Vector2.new(0, 0)
		button.ImageRectSize = rectSize or Vector2.new(0, 0)
		return true
	end
	return false
end

-- Restyle a topbar icon button: new icon, clean square size, soft glow on hover
local function styleIconButton(button, iconName)
	if not button then return end
	applyLucide(button, iconName)
	button.ScaleType = Enum.ScaleType.Fit

	-- Resize to a clean 20x20 square but keep the button's visual centre where the
	-- prebuilt layout put it (works for any AnchorPoint the asset uses).
	local oldSize, anchor = button.AbsoluteSize, button.AnchorPoint
	if oldSize.X > 0 and oldSize.Y > 0 then
		local dx = (20 - oldSize.X) * (0.5 - anchor.X)
		local dy = (20 - oldSize.Y) * (0.5 - anchor.Y)
		button.Position = button.Position + UDim2.fromOffset(dx, dy)
	end
	button.Size = UDim2.new(0, 20, 0, 20)

	local glow = makeGlow(button, SelectedTheme.TextColor, 22)
	local baseTransparency = 0.8

	button.MouseEnter:Connect(function()
		if Hidden or Minimised or not DarkyFX.introDone then return end
		TweenService:Create(button, TweenInfo.new(0.25, Enum.EasingStyle.Exponential), {ImageTransparency = 0.05}):Play()
		TweenService:Create(glow, TweenInfo.new(0.25, Enum.EasingStyle.Exponential), {ImageTransparency = 0.93}):Play()
